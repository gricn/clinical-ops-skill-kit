"""
Generate `docs/development-evidence.md` from a private origin repository.

Aggregates git history into showcase-safe statistics: total commits,
conventional-commit-type breakdown, and per-skill iteration distribution. The
output is the **structural shape** of the private repo's development history —
volume and per-skill activity — without ever exposing commit messages, authors,
emails, hashes, dates, or file contents.

Intended use:
    python scripts/generate_development_evidence.py \\
        --source /path/to/private-origin-repo \\
        --output docs/development-evidence.md

Then `git add docs/development-evidence.md && git commit && git push`.

Hiring managers can verify volume and cadence without needing access to the
private repo.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path


CONVENTIONAL_TYPES = (
    "feat",
    "fix",
    "docs",
    "refactor",
    "chore",
    "test",
    "style",
    "perf",
    "build",
    "ci",
    "revert",
)

# Production aliases are loaded only from an optional, untracked local mapping.
# Unknown names are aggregated; mapping contents are never rendered.
SKILL_NAME_NORMALIZATION = {}
SKILL_PREFIX_NORMALIZATION = {}

# The 15 skills that exist in the public showcase (`skills/catalog/collections.yaml`).
# Anything not in this set after normalization is bucketed as internal, so a
# future private-only skill can never leak into the public evidence file.
PUBLIC_SKILLS = {
    "cathlab-schedule-ocr",
    "gsheet-append-dedup",
    "medical-inventory-tencent-import",
    "warehouse-shipment-planning",
    "warehouse-shipment-dida-task",
    "vendor-sales-inventory-sync",
    "material-complaint-update",
    "spd-confirm-supply",
    "order-shipment",
    "spd-confirm-delivery",
    "vendor-invoice-records",
    "surgery-summary",
    "surgery-volume-summary",
    "task-closeout-standards",
    "tencent-docs-api-v3",
}

INTERNAL_BUCKET = "(other internal modules)"


def normalize_skill_name(raw: str) -> str:
    """Map a private-repo skill folder name to a public, leak-safe label."""
    if raw in SKILL_NAME_NORMALIZATION:
        mapped = SKILL_NAME_NORMALIZATION[raw]
    else:
        mapped = raw
        for prefix, target in SKILL_PREFIX_NORMALIZATION.items():
            if raw.startswith(prefix):
                mapped = target
                break
    return mapped if mapped in PUBLIC_SKILLS else INTERNAL_BUCKET


def git(cwd: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", *args],
        cwd=str(cwd),
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout


def total_commits(repo: Path) -> int:
    return int(git(repo, "rev-list", "--count", "HEAD").strip())


def conventional_type_counts(repo: Path) -> dict[str, int]:
    out = git(repo, "log", "--format=%s")
    counts: Counter[str] = Counter()
    pattern = re.compile(r"^(?P<type>[a-z]+)(\([^)]*\))?!?:")
    for line in out.splitlines():
        m = pattern.match(line)
        if m and m.group("type") in CONVENTIONAL_TYPES:
            counts[m.group("type")] += 1
        else:
            counts["other"] += 1
    return dict(counts.most_common())


def per_skill_touch_counts(repo: Path) -> dict[str, int]:
    """Commits touching each `skills/<name>/` subtree.

    A commit touching N skills counts once per skill. Skill folder names are
    normalized to the public-showcase kebab-case where applicable.
    """
    out = git(repo, "log", "--name-only", "--format=format:__COMMIT__")
    counts: Counter[str] = Counter()
    seen_in_commit: set[str] = set()

    def flush() -> None:
        for skill in seen_in_commit:
            counts[skill] += 1
        seen_in_commit.clear()

    for line in out.splitlines():
        line = line.strip()
        if line == "__COMMIT__":
            flush()
            continue
        if line.startswith("skills/"):
            parts = line.split("/")
            if len(parts) >= 3 and parts[1] != "catalog":
                seen_in_commit.add(normalize_skill_name(parts[1]))
    flush()

    return dict(counts.most_common())


def render_markdown(
    total: int,
    types: dict[str, int],
    per_skill: dict[str, int],
) -> str:
    lines: list[str] = []
    lines.append("# Development evidence")
    lines.append("")
    lines.append(
        "Aggregated, desensitized statistics from the **private origin repository** "
        "this showcase is derived from. Generated by "
        "[`scripts/generate_development_evidence.py`](../scripts/generate_development_evidence.py) "
        "directly against the private repo's git history."
    )
    lines.append("")
    lines.append(
        "**No commit messages, authors, emails, hashes, dates, or file contents are "
        "exposed** — only structural counts. The script is in this public repo, so the "
        "methodology is auditable; the input data stays local."
    )
    lines.append("")
    lines.append("## Scale")
    lines.append("")
    lines.append(f"- Total commits: **{total}**")
    lines.append(
        f"- Public skills with recorded iteration: "
        f"**{sum(1 for s in per_skill if s != INTERNAL_BUCKET)}**"
    )
    lines.append("")
    lines.append("## Conventional-commit type breakdown")
    lines.append("")
    lines.append(
        "Type tags parsed from commit subjects (Conventional Commits format). "
        "This is a **rules-driven automation repo operating against live business "
        "systems** (hospital SPD, Tencent Docs, vendor portals), so the high "
        "`fix` / `docs` share reflects continuously hardening business decision "
        "rules and skill specifications against real-world edge cases — not "
        "bug-chasing on a greenfield codebase. Each `fix` typically encodes a "
        "newly observed exception into an explicit, reusable rule."
    )
    lines.append("")
    lines.append("| Type | Commits | Share |")
    lines.append("| --- | --- | --- |")
    type_total = sum(types.values()) or 1
    for t, count in types.items():
        share = 100.0 * count / type_total
        lines.append(f"| `{t}` | {count} | {share:.1f}% |")
    lines.append("")
    lines.append("## Per-skill iteration")
    lines.append("")
    lines.append(
        "Number of commits that touched each `skills/<name>/` subtree. A commit "
        "touching multiple skills counts once per skill. Folder names are "
        "normalized to match the public showcase's "
        "`skills/catalog/collections.yaml`; private-only sub-modules are bucketed "
        "as `(other internal modules)`."
    )
    lines.append("")
    lines.append("| Skill | Commits touching this skill |")
    lines.append("| --- | --- |")
    for skill, count in per_skill.items():
        lines.append(f"| `{skill}` | {count} |")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append(
        "_Regenerate locally with:_ "
        "`python scripts/generate_development_evidence.py "
        "--source <path-to-private-repo> --output docs/development-evidence.md`"
    )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--source",
        type=Path,
        required=True,
        help="Path to the private origin repo (e.g. /path/to/private-origin-repo).",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "docs" / "development-evidence.md",
        help="Output markdown file (default: ../docs/development-evidence.md).",
    )
    parser.add_argument("--mapping", type=Path, help="Local private JSON with exact and prefixes maps; never commit it.")
    args = parser.parse_args()
    if args.mapping:
        config = json.loads(args.mapping.read_text(encoding="utf-8"))
        for key, target in [("exact", SKILL_NAME_NORMALIZATION), ("prefixes", SKILL_PREFIX_NORMALIZATION)]:
            values = config.get(key, {})
            if not isinstance(values, dict) or any(not isinstance(k, str) or not k or v not in PUBLIC_SKILLS for k, v in values.items()):
                parser.error("Invalid private mapping; destinations must be public skill names.")
            target.update(values)

    repo = args.source.resolve()
    if not (repo / ".git").is_dir():
        print(f"ERROR: {repo} is not a git repository.", file=sys.stderr)
        return 1

    total = total_commits(repo)
    types = conventional_type_counts(repo)
    per_skill = per_skill_touch_counts(repo)

    md = render_markdown(total, types, per_skill)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(md, encoding="utf-8")

    public_skills = sum(1 for s in per_skill if s != INTERNAL_BUCKET)
    print(f"Wrote {args.output}")
    print(f"  total={total}  public_skills={public_skills}  buckets={len(per_skill)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
